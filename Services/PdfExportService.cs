using JournalApp.Data.Models;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

// This avoids conflict between MAUI Colors and QuestPDF Colors
using QColors = QuestPDF.Helpers.Colors;

namespace JournalApp.Services
{
    public class PdfExportService
    {
        // Export a single entry (this is used in EntryDetails and works)
        public string ExportEntryToPdf(JournalEntry entry)
        {
            var safeDate = entry.EntryDate.ToString("yyyy-MM-dd");
            var fileName = $"Journal_{safeDate}.pdf";

            var folder = FileSystem.AppDataDirectory;
            var path = Path.Combine(folder, fileName);

            Document.Create(container =>
            {
                container.Page(page =>
                {
                    page.Size(PageSizes.A4);
                    page.Margin(30);
                    page.DefaultTextStyle(x => x.FontSize(12));

                    page.Header()
                        .Text("Journal Entry")
                        .FontSize(20)
                        .SemiBold();

                    page.Content().Column(col =>
                    {
                        col.Spacing(10);

                        col.Item().Text($"Date: {entry.EntryDate:dd MMM yyyy}")
                            .FontSize(14)
                            .SemiBold();

                        col.Item().Text($"Primary Mood: {entry.PrimaryMood}");

                        if (!string.IsNullOrWhiteSpace(entry.Title))
                            col.Item().Text($"Title: {entry.Title}")
                                      .SemiBold();

                        col.Item().LineHorizontal(1);

                        col.Item().Text("Content:").SemiBold();
                        col.Item().Text(entry.Content ?? "");

                        if (entry.JournalEntryTags != null && entry.JournalEntryTags.Count > 0)
                        {
                            var tagNames = entry.JournalEntryTags
                                .Select(t => t.Tag.Name)
                                .ToList();

                            col.Item().LineHorizontal(1);
                            col.Item().Text("Tags:").SemiBold();
                            col.Item().Text(string.Join(", ", tagNames));
                        }

                        col.Item().LineHorizontal(1);
                        col.Item().Text($"Created: {entry.CreatedAt:dd MMM yyyy HH:mm}");
                        col.Item().Text($"Updated: {entry.UpdatedAt:dd MMM yyyy HH:mm}");
                    });

                    page.Footer()
                        .AlignCenter()
                        .Text("Generated by JournalApp");
                });
            })
            .GeneratePdf(path);

            return path;
        }

        // Export all history into ONE pdf file
        public string ExportAllEntriesToPdf(List<JournalEntry> entries)
        {
            var fileName = $"Journal_All_{DateTime.Now:yyyy-MM-dd_HHmm}.pdf";

            var folder = FileSystem.AppDataDirectory;
            var path = Path.Combine(folder, fileName);

            // Newest saved/edited entries first
            var ordered = entries
                .OrderByDescending(e => e.UpdatedAt)
                .ThenByDescending(e => e.EntryDate)
                .ToList();

            Document.Create(container =>
            {
                container.Page(page =>
                {
                    page.Size(PageSizes.A4);
                    page.Margin(30);
                    page.DefaultTextStyle(x => x.FontSize(12));

                    page.Header()
                        .Text("Journal History")
                        .FontSize(20)
                        .SemiBold();

                    page.Content().Column(col =>
                    {
                        col.Spacing(12);

                        foreach (var e in ordered)
                        {
                            col.Item().Text($"{e.EntryDate:dd MMM yyyy}  •  {e.PrimaryMood}")
                                .FontSize(14)
                                .SemiBold();

                            if (!string.IsNullOrWhiteSpace(e.Title))
                                col.Item().Text($"Title: {e.Title}")
                                    .SemiBold();

                            col.Item().Text(e.Content ?? "");

                            if (e.JournalEntryTags != null && e.JournalEntryTags.Count > 0)
                            {
                                var tagNames = e.JournalEntryTags
                                    .Select(t => t.Tag.Name)
                                    .ToList();

                                col.Item().Text("Tags: " + string.Join(", ", tagNames));
                            }

                            // This line caused your error before. Now it's fixed using QColors alias.
                            col.Item().Text($"Updated: {e.UpdatedAt:dd MMM yyyy HH:mm}")
                                .FontSize(10)
                                .FontColor(QColors.Grey.Darken2);

                            col.Item().LineHorizontal(1);
                        }
                    });

                    page.Footer()
                        .AlignCenter()
                        .Text("Generated by JournalApp");
                });
            })
            .GeneratePdf(path);

            return path;
        }
    }
}
